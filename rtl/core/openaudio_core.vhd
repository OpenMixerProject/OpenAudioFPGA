-- Vendor-neutral audio core: audio clock tree, TDM8 serialisers, routing matrix,
-- control bus (SPI -> Wishbone), a configurable number of AES50 cores and an optional
-- AES67 core.
--
-- This entity contains no vendor primitives (no PLLs, no DDR / IO registers, no
-- clock buffers). Everything that depends on the FPGA family or on the console
-- belongs into the layers above:
--
--   platforms/<console>_<fpga>   top level: pins, PLLs, IO registers, constraints
--   consoles/<console>           console specific, but vendor-neutral logic
--   rtl/core (this file)         generic core
--
-- Audio lines
-- -----------
-- The unit of the matrix is the "TDM line": one serial TDM8 stream with
-- 8 channels of 24 bit in 32 bit slots, clocked with 256 fs.
--
--   inputs  (sources):      G_TDM_LINES_IN  lines = 8 * G_TDM_LINES_IN  channels
--   outputs (destinations): G_TDM_LINES_OUT lines = 8 * G_TDM_LINES_OUT channels
--
-- The AES50 cores sit on the same lines: core k (0 .. G_AES50_PORTS - 1) uses the
-- 6 lines G_AES50_FIRST_LINE + 6 * k .. + 5 in both directions (48 channels).
-- The AES67 core (G_AES67) does the same with the 4 lines G_AES67_FIRST_LINE .. + 3
-- (32 channels). For the lines of both the bits of tdm_i are ignored; tdm_o
-- still carries the data. All other lines are free for the layer above
-- (converters, DSPs, cards, ...).
--
-- The network cores are instantiated here, but they keep their own source
-- trees: rtl/aes50 for AES50, the AES67 repository for AES67 (component
-- aes67_openaudiofpga). Without G_AES67 the AES67 sources are not needed.
-- Which vendor variant of their IO / RAM / SoC files is used is decided by the
-- file list of the platform, not here.
--
-- Control bus
-- -----------
-- One bus for everything the host configures: SPIBone (LiteX, 4 wire SPI, mode 0,
-- MSB first) -> Wishbone crossbar, generated by litex_soc/generate.py (component
-- openaudio_soc, clocked with clk50_i). Byte addresses, 32 bit words:
--
--   0x00000000  CSRs: ctrl (reset, scratch, bus errors), core (info, version, config)
--               -> litex_soc/build/<family>/csr.csv
--   0x80000000  routing matrix, one word per destination (routing_wb.vhd):
--                 word address line * 8 + channel (destination)
--                 data 0 = off, line * 8 + channel + 1 = source
--   0x90000000  AES67 core (128 KiB): its register window, csr.csv of its aes67_bridge
--               target. Without G_AES67 the window answers with a bus error.
--
-- SPIBone samples the SPI pins with clk50_i: keep SCLK at or below clk50_i / 12
-- (the i.MX25 gives 4.16 MHz for an 8 MHz request).

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity openaudio_core is
	generic (
		-- matrix size
		G_TDM_LINES_IN			: positive := 24;		-- TDM8 input lines (8 channels each)
		G_TDM_LINES_OUT			: positive := 24;		-- TDM8 output lines (8 channels each)

		-- AES50
		G_AES50_PORTS			: natural := 1;			-- number of AES50 cores (0 = none)
		G_AES50_FIRST_LINE		: natural := 14;		-- first TDM line of AES50 core 0
		G_AES50_SUPPORT_44K1	: boolean := false;		-- false: half-size sample RAMs, 48k only
		G_AES50_UART_AUX		: boolean := true;		-- aux channel over UART
		G_AES50_TDM_AUX			: boolean := true;		-- aux channel over the 7th TDM line
		G_AES50_UART_FIFO_AW	: natural := 11;		-- UART FIFOs: 2**n - 1 bytes
		G_AES50_UART_BAUD		: positive := 115200;	-- baudrate of the aux UARTs
		G_AES50_SIM_ASSM_SAMPLES	: natural := 2048;	-- simulation only: shorter ASSM period

		-- AES67
		G_AES67					: boolean := false;		-- with AES67 core
		G_AES67_FIRST_LINE		: natural := 20;		-- first of its 4 TDM lines

		-- identification (CSR core_info)
		G_PLATFORM_ID			: natural range 0 to 255 := 0;	-- 1 = X32 Lattice, 2 = X32 Spartan

		-- audio clock tree (see audioclk.vhd). With the AES67 core the divider follows its
		-- frame sync (PTP), else fs_sync_i.
		G_FS_SYNC_CNT			: natural range 0 to 511 := 0;
		G_FS_ADVANCE			: natural range 0 to 511 := 3;
		G_FRAME_ROUTES : natural := 0;
		G_DSP_LANES : positive := 1;
		G_DSP_RX_USED, G_DSP_TX_USED : std_logic_vector(15 * G_DSP_LANES - 1 downto 0) := (others => '0')
	);
	port (
		-- audio clocks
		clk_fs1024_i		: in  std_logic;			-- 1024 fs (49.152 MHz at 48 kHz) from the audio PLL
		fs_sync_i			: in  std_logic := '0';		-- optional: frame sync of an external clock master, '0' = free running
														-- (not used with G_AES67)
		clk_fs512_o			: out std_logic;			-- 512 fs
		clk_fs256_o			: out std_logic;			-- 256 fs = TDM8 bit clock
		fsync_o				: out std_logic;			-- fs = TDM8 frame sync

		frame_reset_i : in std_logic := '0';
		frame_phase_o : out unsigned(9 downto 0);
		dsp_tdm_i, dsp_valid_i : in std_logic_vector(G_DSP_LANES - 1 downto 0) := (others => '0');
		dsp_tdm_o : out std_logic_vector(G_DSP_LANES - 1 downto 0);
		dsp_tx_enable_i : in std_logic_vector(G_DSP_LANES - 1 downto 0) := (others => '1');
		dsp_reset_release_o, dsp_audio_enable_o, dsp_audio_valid_o : out std_logic_vector(3 downto 0);
		frame_ready_o : out std_logic;
		frame_status_extra_i : in std_logic := '0'; -- benchmark observation only

		-- control bus (SPIBone, see above; clocked with clk50_i)
		spi_ncs_i			: in  std_logic;
		spi_clk_i			: in  std_logic;
		spi_mosi_i			: in  std_logic;
		spi_miso_o			: out std_logic;			-- '0' while spi_ncs_i = '1'
		cfg_bits_o			: out std_logic_vector(7 downto 0);	-- CSR core_config (clk50_i domain)

		-- TDM8 lines
		tdm_i				: in  std_logic_vector(G_TDM_LINES_IN - 1 downto 0);
		tdm_o				: out std_logic_vector(G_TDM_LINES_OUT - 1 downto 0);
		-- the current channel of every output line as a parallel word (e.g. for UltraNet)
		tdm_par_o			: out std_logic_vector(G_TDM_LINES_OUT * 24 - 1 downto 0);

		-- 50 MHz: RMII clock of the network cores and clock of the control bus
		clk50_i				: in  std_logic;

		-- AES50 (one element / pair per core, unused if G_AES50_PORTS = 0)
		aes50_rst_i			: in  std_logic := '1';
		aes50_fs_mode_i		: in  std_logic_vector(1 downto 0) := "01";		-- "01" = 48 kHz
		aes50_sys_mode_i	: in  std_logic_vector(2 * G_AES50_PORTS - 1 downto 0) := (others => '0');
		aes50_aux_uart_sel_i	: in  std_logic_vector(G_AES50_PORTS - 1 downto 0) := (others => '1');	-- aux TX: '1' = UART, '0' = TDM

		aes50_rmii_crs_dv_i	: in  std_logic_vector(G_AES50_PORTS - 1 downto 0) := (others => '0');
		aes50_rmii_rxd_i	: in  std_logic_vector(2 * G_AES50_PORTS - 1 downto 0) := (others => '0');
		aes50_rmii_tx_en_o	: out std_logic_vector(G_AES50_PORTS - 1 downto 0);
		aes50_rmii_txd_o	: out std_logic_vector(2 * G_AES50_PORTS - 1 downto 0);
		aes50_phy_rst_n_o	: out std_logic_vector(G_AES50_PORTS - 1 downto 0);

		aes50_clk_a_rx_i	: in  std_logic_vector(G_AES50_PORTS - 1 downto 0) := (others => '0');
		aes50_clk_a_tx_o	: out std_logic_vector(G_AES50_PORTS - 1 downto 0);
		aes50_clk_a_tx_en_o	: out std_logic_vector(G_AES50_PORTS - 1 downto 0);
		aes50_clk_b_rx_i	: in  std_logic_vector(G_AES50_PORTS - 1 downto 0) := (others => '0');
		aes50_clk_b_tx_o	: out std_logic_vector(G_AES50_PORTS - 1 downto 0);
		aes50_clk_b_tx_en_o	: out std_logic_vector(G_AES50_PORTS - 1 downto 0);

		aes50_tdm_aux_i		: in  std_logic_vector(G_AES50_PORTS - 1 downto 0) := (others => '0');	-- 7th TDM line (aux data)
		aes50_tdm_aux_o		: out std_logic_vector(G_AES50_PORTS - 1 downto 0);
		aes50_uart_i		: in  std_logic_vector(G_AES50_PORTS - 1 downto 0) := (others => '1');
		aes50_uart_o		: out std_logic_vector(G_AES50_PORTS - 1 downto 0);
		aes50_ok_o			: out std_logic_vector(G_AES50_PORTS - 1 downto 0);

		-- AES67 (unused without G_AES67, the outputs are '0' then)
		-- RMII with clk50_i; registers on the control bus (0x90000000)
		clk100_i			: in  std_logic := '0';		-- 100 MHz system clock of the AES67 core
		aes67_rst_n_i		: in  std_logic := '0';		-- '1' when the clocks are stable
		aes67_rmii_crs_dv_i	: in  std_logic := '0';
		aes67_rmii_rxd_i	: in  std_logic_vector(1 downto 0) := (others => '0');
		aes67_rmii_tx_en_o	: out std_logic;
		aes67_rmii_txd_o	: out std_logic_vector(1 downto 0);
		aes67_irq_o			: out std_logic;
		-- PTP disciplined 512 fs clock: reference for the audio PLL that generates clk_fs1024_i
		aes67_pll_ref_o		: out std_logic
	);
end entity openaudio_core;

architecture rtl of openaudio_core is
	constant C_DATA_WIDTH	: integer := 24;
	-- channel numbers of the matrix (destinations and sources + 1)
	function addr_width return positive is
	begin
		if G_FRAME_ROUTES > 0 then return 10; else return 8; end if;
	end;
	constant C_ADDR_WIDTH : integer := addr_width;
	-- CSR core_version: bump when the register map of the control bus changes
	constant C_VERSION		: std_logic_vector(31 downto 0) := x"00030000";
	constant C_AES50_LINES	: natural := 6;		-- TDM lines per AES50 core (48 channels)
	constant C_AES67_LINES	: natural := 4;		-- TDM lines of the AES67 core (32 channels)

	-- timer values of the AES50 cores, counted in clocks of the 50 MHz RMII clock
	constant C_CLK50_HZ			: natural := 50000000;
	constant C_AES50_UART_CLKS	: natural := (C_CLK50_HZ + G_AES50_UART_BAUD / 2) / G_AES50_UART_BAUD;
	constant C_AES50_10MS		: natural := C_CLK50_HZ / 100;
	constant C_AES50_1MS		: natural := C_CLK50_HZ / 1000;

	signal clk_fs512		: std_logic;
	signal clk_fs256		: std_logic;
	signal fsync			: std_logic;
	signal fs_sync			: std_logic;
	signal aes67_fsync		: std_logic;

	-- Wishbone buses of the control bus (master: openaudio_soc)
	type t_wb_m2s is record
		adr		: std_logic_vector(29 downto 0);
		dat		: std_logic_vector(31 downto 0);
		sel		: std_logic_vector(3 downto 0);
		cyc		: std_logic;
		stb		: std_logic;
		we		: std_logic;
		cti		: std_logic_vector(2 downto 0);
		bte		: std_logic_vector(1 downto 0);
	end record;
	type t_wb_s2m is record
		dat		: std_logic_vector(31 downto 0);
		ack		: std_logic;
		err		: std_logic;
	end record;

	signal routing_m2s		: t_wb_m2s;
	signal routing_s2m		: t_wb_s2m;
	signal aes67_m2s		: t_wb_m2s;
	signal aes67_s2m		: t_wb_s2m;
	signal core_info		: std_logic_vector(31 downto 0);
	signal soc_miso			: std_logic;
	signal soc_clk, matrix_clk, frame_scan, route_ready : std_logic;
	signal wing_status : std_logic_vector(31 downto 0) := (others => '0');
	signal aes50_ok : std_logic_vector(G_AES50_PORTS - 1 downto 0);

	signal tdm_rx			: std_logic_vector(G_TDM_LINES_IN - 1 downto 0);
	signal tdm_tx			: std_logic_vector(G_TDM_LINES_OUT - 1 downto 0);
	signal rx_par			: std_logic_vector(G_TDM_LINES_IN * C_DATA_WIDTH - 1 downto 0);
	signal tx_par			: std_logic_vector(G_TDM_LINES_OUT * C_DATA_WIDTH - 1 downto 0);

	signal ram_wr_en		: std_logic;
	signal ram_wr_addr		: std_logic_vector(C_ADDR_WIDTH - 1 downto 0);
	signal ram_wr_data		: std_logic_vector(C_DATA_WIDTH - 1 downto 0);
	signal ram_rd_addr		: std_logic_vector(C_ADDR_WIDTH - 1 downto 0);
	signal ram_rd_data		: std_logic_vector(C_DATA_WIDTH - 1 downto 0);
	signal channel_idx		: std_logic_vector(C_ADDR_WIDTH - 1 downto 0);

	-- control SoC (litex_soc/generate.py, Verilog: litex_soc/build/<family>/gateware/openaudio_soc.v)
	component openaudio_soc
		port (
			clk_sys				: in  std_logic;
			spibone_clk			: in  std_logic;
			spibone_cs_n		: in  std_logic;
			spibone_mosi		: in  std_logic;
			spibone_miso		: out std_logic;
			core_info			: in  std_logic_vector(31 downto 0);
			core_version		: in  std_logic_vector(31 downto 0);
			core_config			: out std_logic_vector(7 downto 0);
			wing_status : in std_logic_vector(31 downto 0);
			wing_reset_release, wing_audio_enable, wing_audio_valid : out std_logic_vector(3 downto 0);
			routing_wb_adr		: out std_logic_vector(29 downto 0);
			routing_wb_dat_w	: out std_logic_vector(31 downto 0);
			routing_wb_dat_r	: in  std_logic_vector(31 downto 0);
			routing_wb_sel		: out std_logic_vector(3 downto 0);
			routing_wb_cyc		: out std_logic;
			routing_wb_stb		: out std_logic;
			routing_wb_we		: out std_logic;
			routing_wb_cti		: out std_logic_vector(2 downto 0);
			routing_wb_bte		: out std_logic_vector(1 downto 0);
			routing_wb_ack		: in  std_logic;
			routing_wb_err		: in  std_logic;
			aes67_wb_adr		: out std_logic_vector(29 downto 0);
			aes67_wb_dat_w		: out std_logic_vector(31 downto 0);
			aes67_wb_dat_r		: in  std_logic_vector(31 downto 0);
			aes67_wb_sel		: out std_logic_vector(3 downto 0);
			aes67_wb_cyc		: out std_logic;
			aes67_wb_stb		: out std_logic;
			aes67_wb_we			: out std_logic;
			aes67_wb_cti		: out std_logic_vector(2 downto 0);
			aes67_wb_bte		: out std_logic_vector(1 downto 0);
			aes67_wb_ack		: in  std_logic;
			aes67_wb_err		: in  std_logic);
	end component;

	-- AES67 core (AES67 repository, FPGA/boards/integration/aes67_openaudiofpga.vhd).
	-- A component, so that the core compiles without the AES67 sources if not G_AES67.
	component aes67_openaudiofpga
		port (
			sys_clk_i		: in  std_logic;
			rst_n_i			: in  std_logic;
			ext_mcu_clk_i	: in  std_logic;
			ext_locked_i	: in  std_logic;
			rmii_ref_clk_i	: in  std_logic;
			rmii_crs_dv_i	: in  std_logic;
			rmii_rxd_i		: in  std_logic_vector(1 downto 0);
			rmii_tx_en_o	: out std_logic;
			rmii_txd_o		: out std_logic_vector(1 downto 0);
			mclk_o			: out std_logic;
			bclk_o			: out std_logic;
			fsync_adc_o		: out std_logic;
			fsync_dac_o		: out std_logic;
			tdm_in_i		: in  std_logic_vector(3 downto 0);
			tdm_out_o		: out std_logic_vector(3 downto 0);
			pll_ref_o		: out std_logic;
			ext_mclk_i		: in  std_logic;
			wb_adr_i		: in  std_logic_vector(29 downto 0);
			wb_dat_i		: in  std_logic_vector(31 downto 0);
			wb_dat_o		: out std_logic_vector(31 downto 0);
			wb_sel_i		: in  std_logic_vector(3 downto 0);
			wb_cyc_i		: in  std_logic;
			wb_stb_i		: in  std_logic;
			wb_we_i			: in  std_logic;
			wb_cti_i		: in  std_logic_vector(2 downto 0);
			wb_bte_i		: in  std_logic_vector(1 downto 0);
			wb_ack_o		: out std_logic;
			wb_err_o		: out std_logic;
			irq_o			: out std_logic);
	end component;

	-- true if this line is driven by an AES50 / AES67 core instead of tdm_i
	function is_aes50_line(line : natural) return boolean is
	begin
		return (line >= G_AES50_FIRST_LINE) and (line < G_AES50_FIRST_LINE + C_AES50_LINES * G_AES50_PORTS);
	end function;

	function f_aes67_bit return std_logic is
	begin
		if G_AES67 then
			return '1';
		end if;
		return '0';
	end function;

	function is_aes67_line(line : natural) return boolean is
	begin
		return G_AES67 and (line >= G_AES67_FIRST_LINE) and (line < G_AES67_FIRST_LINE + C_AES67_LINES);
	end function;
begin
	-- the matrix needs at least two lines (the RAM writer always handles a second receiver),
	-- source 0 is "off"
	assert G_TDM_LINES_IN >= 2 and G_TDM_LINES_OUT >= 2
		report "openaudio_core: at least 2 TDM lines per direction are required" severity failure;
	assert 8 * G_TDM_LINES_IN <= 2**C_ADDR_WIDTH - 1
		report "openaudio_core: too many input lines for 8 bit source numbers (max. 31)" severity failure;
	assert 8 * G_TDM_LINES_OUT <= 2**C_ADDR_WIDTH - 1
		report "openaudio_core: too many output lines for 8 bit addresses (max. 31)" severity failure;
	assert G_AES50_PORTS = 0 or
		(G_AES50_FIRST_LINE + C_AES50_LINES * G_AES50_PORTS <= G_TDM_LINES_IN and
		 G_AES50_FIRST_LINE + C_AES50_LINES * G_AES50_PORTS <= G_TDM_LINES_OUT)
		report "openaudio_core: the AES50 lines do not fit into the matrix" severity failure;
	assert not G_AES67 or
		(G_AES67_FIRST_LINE + C_AES67_LINES <= G_TDM_LINES_IN and
		 G_AES67_FIRST_LINE + C_AES67_LINES <= G_TDM_LINES_OUT)
		report "openaudio_core: the AES67 lines do not fit into the matrix" severity failure;
	assert G_AES50_PORTS = 0 or not G_AES67 or
		G_AES50_FIRST_LINE + C_AES50_LINES * G_AES50_PORTS <= G_AES67_FIRST_LINE or
		G_AES67_FIRST_LINE + C_AES67_LINES <= G_AES50_FIRST_LINE
		report "openaudio_core: the AES50 and AES67 lines overlap" severity failure;

	------------------------------------------------------------------------
	-- audio clock tree
	------------------------------------------------------------------------
	gen_fs_sync_aes67 : if G_AES67 generate
		fs_sync <= aes67_fsync;
	end generate;

	gen_fs_sync_ext : if not G_AES67 generate
		fs_sync <= fs_sync_i;
	end generate;

	legacy_clock : if G_FRAME_ROUTES = 0 generate
	soc_clk <= clk50_i;
	matrix_clk <= clk_fs512;
	frame_scan <= '0';
	frame_phase_o <= (others => '0');
	dsp_tdm_o <= (others => '0');
	u_audioclk : entity work.audioclk
		generic map (
			AES67_SYNC_CNT => G_FS_SYNC_CNT,
			FS_ADVANCE => G_FS_ADVANCE)
		port map (
			clock_to_aes67_i => '1',
			aes67_fs_i => fs_sync,
			aes67_bclk_i => '0',
			fs_x_1024_i => clk_fs1024_i,
			fs_x_512_o => clk_fs512,
			fs_x_256_o => clk_fs256,
			fs_x_128_o => open,
			fs_x_64_o => open,
			fs_o => fsync);
	end generate;

	clk_fs512_o <= clk_fs512;
	clk_fs256_o <= clk_fs256;
	fsync_o <= fsync;

	------------------------------------------------------------------------
	-- control bus: SPIBone -> Wishbone (clk50_i)
	------------------------------------------------------------------------
	core_info <= std_logic_vector(to_unsigned(G_PLATFORM_ID, 8))
			   & "000" & f_aes67_bit
			   & std_logic_vector(to_unsigned(G_AES50_PORTS, 4))
			   & std_logic_vector(to_unsigned(G_TDM_LINES_OUT, 8))
			   & std_logic_vector(to_unsigned(G_TDM_LINES_IN, 8));

	u_soc : openaudio_soc
		port map (
			clk_sys => soc_clk,
			spibone_clk => spi_clk_i,
			spibone_cs_n => spi_ncs_i,
			spibone_mosi => spi_mosi_i,
			spibone_miso => soc_miso,
			core_info => core_info,
			core_version => C_VERSION,
			core_config => cfg_bits_o,
			wing_status => wing_status,
			wing_reset_release => dsp_reset_release_o,
			wing_audio_enable => dsp_audio_enable_o,
			wing_audio_valid => dsp_audio_valid_o,
			routing_wb_adr => routing_m2s.adr,
			routing_wb_dat_w => routing_m2s.dat,
			routing_wb_dat_r => routing_s2m.dat,
			routing_wb_sel => routing_m2s.sel,
			routing_wb_cyc => routing_m2s.cyc,
			routing_wb_stb => routing_m2s.stb,
			routing_wb_we => routing_m2s.we,
			routing_wb_cti => routing_m2s.cti,
			routing_wb_bte => routing_m2s.bte,
			routing_wb_ack => routing_s2m.ack,
			routing_wb_err => routing_s2m.err,
			aes67_wb_adr => aes67_m2s.adr,
			aes67_wb_dat_w => aes67_m2s.dat,
			aes67_wb_dat_r => aes67_s2m.dat,
			aes67_wb_sel => aes67_m2s.sel,
			aes67_wb_cyc => aes67_m2s.cyc,
			aes67_wb_stb => aes67_m2s.stb,
			aes67_wb_we => aes67_m2s.we,
			aes67_wb_cti => aes67_m2s.cti,
			aes67_wb_bte => aes67_m2s.bte,
			aes67_wb_ack => aes67_s2m.ack,
			aes67_wb_err => aes67_s2m.err);

	-- MISO is shared with nothing else: drive it only while selected
