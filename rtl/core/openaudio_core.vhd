	-- true if this line is driven by an AES50 / AES67 core instead of tdm_i
	function is_aes50_line(line : natural) return boolean is
	begin
		return (line >= G_AES50_FIRST_LINE) and (line < G_AES50_FIRST_LINE + C_AES50_LINES * G_AES50_PORTS);
	end function;

	function f_aes67_bit return std_logic is
	begin
		if G_AES67 then
			return '1';
		end if;
		return '0';
	end function;

	function f_inferno_bit return std_logic is
	begin
		if G_INFERNO then
			return '1';
		end if;
		return '0';
	end function;

	function f_aes50_src_bit return std_logic is
	begin
		if G_AES50_PAR_BRIDGE and G_AES50_ENABLE_SRC then
			return '1';
		end if;
		return '0';
	end function;

	function is_aes67_line(line : natural) return boolean is
	begin
		return G_AES67 and (line >= G_AES67_FIRST_LINE) and (line < G_AES67_FIRST_LINE + C_AES67_LINES);
	end function;

